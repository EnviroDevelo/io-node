"""gen_tc_nist.py - write drivers/tc_nist_tab.c, the NIST ITS-90 thermocouple reference functions
(NIST SRD 60, public domain) for types K, J, T, E and S, from the thermocouples_reference package
(PyPI, version 0.20, module source_NIST.py, generated by its author from NIST's tables).

    pip download --no-deps thermocouples_reference==0.20 && tar xzf thermocouples_reference-0.20.tar.gz
    python3 -I tools/gen_tc_nist.py thermocouples_reference-0.20 > drivers/tc_nist_tab.c

Also writes tests/tc_nist_ref.h (with --ref): reference points evaluated here with numpy from the
same tables, for the host tests."""
import sys, importlib.util, os

root = sys.argv[1]
spec = importlib.util.spec_from_file_location(
    'thermocouples_reference', os.path.join(root, 'thermocouples_reference', '__init__.py'),
    submodule_search_locations=[os.path.join(root, 'thermocouples_reference')])
mod = importlib.util.module_from_spec(spec)
sys.modules['thermocouples_reference'] = mod
spec.loader.exec_module(mod)
from thermocouples_reference import source_NIST as src
import numpy as np

TYPES = 'KJTES'

def emit_tab():
    print('/* tc_nist_tab.c - GENERATED by tools/gen_tc_nist.py: do not edit.')
    print(' * NIST ITS-90 thermocouple reference functions (NIST SRD 60, public domain): E(T) in mV for T in degC,')
    print(' * piecewise polynomials, lowest order first, plus type K\'s exponential term above 0 degC. */')
    print('#include "temp_conv.h"\n')
    for t in TYPES:
        f = src.thermocouples[t].func
        for i, (lo, hi, coefs, ex) in enumerate(f.table):
            c = list(coefs)[::-1]
            print('static const double %s%d[] = {' % (t, i))
            for k in range(0, len(c), 3):
                print('    ' + ', '.join('%.12e' % v for v in c[k:k + 3]) + ',')
            print('};')
        print('static const tc_piece_t pieces_%s[] = {' % t)
        for i, (lo, hi, coefs, ex) in enumerate(f.table):
            exs = '{ %.12e, %.12e, %.12e }' % tuple(ex) if ex is not None else '{ 0, 0, 0 }'
            print('    { %.3f, %.3f, %s%d, %d, %s },' % (lo, hi, t, i, len(coefs), exs))
        print('};')
    print('\nconst tc_table_t tc_nist[TC_N_TYPES] = {')
    for t in TYPES:
        f = src.thermocouples[t].func
        print('    { pieces_%s, %d },' % (t, len(f.table)))
    print('};')

def emit_ref():
    print('/* tc_nist_ref.h - GENERATED by tools/gen_tc_nist.py --ref: reference points (degC, mV) from the')
    print(' * thermocouples_reference package (NIST SRD 60), for the host tests. Order: K J T E S. */')
    pts = {'K': [-200, -100, -20, 0, 25, 100, 250, 500, 800, 1000, 1300],
           'J': [-200, -50, 0, 30, 200, 500, 760, 900, 1150],
           'T': [-200, -100, 0, 20, 100, 250, 390],
           'E': [-200, -50, 0, 40, 300, 600, 950],
           'S': [-40, 0, 100, 600, 1000, 1100, 1500, 1700]}
    print('static const struct { int type; double t, mv; } tc_ref[] = {')
    for i, t in enumerate(TYPES):
        f = src.thermocouples[t].func
        for T in pts[t]:
            for lo, hi, coefs, ex in f.table:
                if lo <= T <= hi:
                    e = float(np.polyval(coefs, T))
                    if ex is not None:
                        e += ex[0] * np.exp(ex[1] * (T - ex[2]) ** 2)
                    break
            print('    { %d, %.1f, %.9f },' % (i, T, e))
    print('};')

if '--ref' in sys.argv:
    emit_ref()
else:
    emit_tab()
